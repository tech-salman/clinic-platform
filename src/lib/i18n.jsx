const LangContext = createContext(null)

export function LanguageProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try { return localStorage.getItem('clinic-lang') || 'ru' } catch { return 'ru' }
  })
  useEffect(() => {
    try { localStorage.setItem('clinic-lang', lang) } catch { /* ignore */ }
  }, [lang])
  const t = (key) => (dict[lang] && dict[lang][key]) || dict.ru[key] || key
  const toggleLang = () => setLang((l) => (l === 'ru' ? 'en' : 'ru'))
  return <LangContext.Provider value={{ lang, setLang, toggleLang, t }}>{children}</LangContext.Provider>
}

export function useLang() {
  const ctx = useContext(LangContext)
  if (!ctx) return { lang: 'ru', setLang: () => {}, toggleLang: () => {}, t: (k) => (dict.ru[k] || k) }
  return ctx
}

// One-click language toggle. Shows the language you will switch TO.
export function LangToggle() {
  const { lang, toggleLang } = useLang()
  return (
    <button type="button" onClick={toggleLang} className="btn-outline !px-3 !py-2" aria-label="Switch language">
      {lang === 'ru' ? 'English' : 'Roman Urdu'}
    </button>
  )
}
